using Microsoft.AspNetCore.Mvc;
using VNPAY.NET;
using VNPAY.NET.Enums;
using VNPAY.NET.Models;
using VNPAY.NET.Utilities;
namespace payment_service.Controllers
{
    [ApiController]
    [Route("[controller]")]
    public class VnpayController : ControllerBase
    {
        private readonly IVnpay _vnpay;
        private readonly IConfiguration _configuration;

        public VnpayController(IVnpay vnPayservice, IConfiguration configuration)
        {
            _vnpay = vnPayservice;
            _configuration = configuration;

            _vnpay.Initialize(_configuration["Vnpay:TmnCode"], _configuration["Vnpay:HashSecret"], _configuration["Vnpay:BaseUrl"], _configuration["Vnpay:CallbackUrl"]);
        }

        /// <summary>
        /// Tạo url thanh toán
        /// </summary>
        /// <param name="money">Số tiền phải thanh toán</param>
        /// <param name="description">Mô tả giao dịch</param>
        /// <returns></returns>
        [HttpGet("CreatePaymentUrl")]
        public ActionResult<string> CreatePaymentUrl(double money, string description)
        {
            try
            {
                var ipAddress = NetworkHelper.GetIpAddress(HttpContext); // Lấy địa chỉ IP của thiết bị thực hiện giao dịch

                var request = new PaymentRequest
                {
                    PaymentId = DateTime.Now.Ticks,
                    Money = money,
                    Description = description,
                    IpAddress = ipAddress,
                    BankCode = BankCode.ANY, // Tùy chọn. Mặc định là tất cả phương thức giao dịch
                    CreatedDate = DateTime.Now, // Tùy chọn. Mặc định là thời điểm hiện tại
                    Currency = Currency.VND, // Tùy chọn. Mặc định là VND (Việt Nam đồng)
                    Language = DisplayLanguage.Vietnamese // Tùy chọn. Mặc định là tiếng Việt
                };

                var paymentUrl = _vnpay.GetPaymentUrl(request);

                return Created(paymentUrl, paymentUrl);
            }
            catch (Exception ex)
            {
                return BadRequest(ex.Message);
            }
        }

        /// <summary>
        /// Thực hiện hành động sau khi thanh toán. URL này cần được khai báo với VNPAY để API này hoạt đồng (ví dụ: h)
        /// </summary>
        /// <returns></returns>
        [HttpGet("IpnAction")]
        public IActionResult IpnAction()
        {
            if (Request.QueryString.HasValue)
            {
                try
                {
                    var paymentResult = _vnpay.GetPaymentResult(Request.Query);
                    if (paymentResult.IsSuccess)
                    {
                        // Thực hiện hành động nếu thanh toán thành công tại đây. Ví dụ: Cập nhật trạng thái đơn hàng trong cơ sở dữ liệu.
                        return Ok();
                    }
                    // Thực hiện hành động nếu thanh toán thất bại tại đây. Ví dụ: Hủy đơn hàng.
                    return BadRequest("Thanh toán thất bại");
                }
                catch (Exception ex)
                {
                    return BadRequest(ex.Message);
                }
            }

            return NotFound("Không tìm thấy thông tin thanh toán.");
        }

        /// <summary>
        /// Trả kết quả thanh toán về cho người dùng
        /// Backend xử lý callback và redirect về frontend với query params
        /// </summary>
        /// <returns></returns>
        [HttpGet("Callback")]
        public IActionResult Callback()
        {
            if (Request.QueryString.HasValue)
            {
                try
                {
                    var paymentResult = _vnpay.GetPaymentResult(Request.Query);

                    // Get frontend URL from configuration, default to localhost:3000
                    var frontendUrl = _configuration["Vnpay:FrontendUrl"] ?? "http://localhost:3000";
                    var frontendCallbackPath = _configuration["Vnpay:FrontendCallbackPath"] ?? "/patient/appointments";

                    // Build redirect URL with all VNPay query parameters
                    var queryString = Request.QueryString.ToString();
                    var redirectUrl = $"{frontendUrl}{frontendCallbackPath}{queryString}";

                    // Redirect to frontend with query params
                    return Redirect(redirectUrl);
                }
                catch (Exception ex)
                {
                    // On error, still redirect to frontend but with error info
                    var frontendUrl = _configuration["Vnpay:FrontendUrl"] ?? "http://localhost:3000";
                    var frontendCallbackPath = _configuration["Vnpay:FrontendCallbackPath"] ?? "/patient/appointments";
                    var errorQuery = $"?vnp_ResponseCode=99&error={Uri.EscapeDataString(ex.Message)}";
                    return Redirect($"{frontendUrl}{frontendCallbackPath}{errorQuery}");
                }
            }

            // No query string, redirect to frontend anyway
            var defaultFrontendUrl = _configuration["Vnpay:FrontendUrl"] ?? "http://localhost:3000";
            var defaultFrontendCallbackPath = _configuration["Vnpay:FrontendCallbackPath"] ?? "/patient/appointments";
            return Redirect($"{defaultFrontendUrl}{defaultFrontendCallbackPath}");
        }
    }
}